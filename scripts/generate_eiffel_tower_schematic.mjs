// Generates bot/schematics/eiffel_tower.json (agorokh/hermescraft#592).
//
// The tower is four mirrored quarters. Each quarter is one named section of
// exactly 150 blocks that stands on its own from the ground to the tip, so one
// character can build a quarter alone and two characters can share the tower.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const outFile = join(__dirname, '..', 'bot', 'schematics', 'eiffel_tower.json');

const HALF = 8; // 16 x 16 footprint
const QUARTER_BLOCKS = 150;
const FRAME = 'iron_block';
const DECK = 'smooth_stone';
const LIGHT = 'sea_lantern';

// One quarter in local coordinates: u and v count outward from the tower's
// centre line (0 is the cell touching the centre), y counts up from the ground.
function quarter() {
  const cells = new Map();
  const put = (u, y, v, block) => { cells.set(`${u},${y},${v}`, [u, y, v, block]); };
  const square = (lo, hi, y, block) => {
    for (let u = lo; u <= hi; u++) for (let v = lo; v <= hi; v++) put(u, y, v, block);
  };

  // Foot pad, then a 2 x 2 leg leaning in one cell every two levels.
  square(5, 7, 0, DECK);
  for (let y = 0; y <= 7; y++) {
    const lo = 6 - Math.floor(y / 2);
    square(lo, lo + 1, y, FRAME);
  }

  // The arch under the first deck.
  for (const [a, y] of [[3, 6], [4, 6], [0, 7], [1, 7], [2, 7], [3, 7]]) {
    put(5, y, a, FRAME);
    put(a, y, 5, FRAME);
  }
  put(5, 6, 5, FRAME);

  // First deck: leg heads, an outer ring, two beams to the centre, a rail.
  square(3, 4, 8, FRAME);
  for (let a = 0; a <= 5; a++) { put(5, 8, a, DECK); put(a, 8, 5, DECK); }
  for (let a = 0; a <= 4; a++) { put(a, 8, 0, DECK); put(0, 8, a, DECK); }
  for (const a of [1, 3]) { put(5, 9, a, FRAME); put(a, 9, 5, FRAME); }
  put(5, 9, 5, LIGHT);

  // Middle leg, stepping in once more.
  for (let y = 9; y <= 11; y++) { put(3, y, 3, FRAME); put(2, y, 3, FRAME); put(3, y, 2, FRAME); }
  put(2, 11, 2, FRAME);
  for (let y = 12; y <= 15; y++) { put(2, y, 2, FRAME); put(1, y, 2, FRAME); put(2, y, 1, FRAME); }
  for (const y of [12, 13]) { put(2, y, 0, FRAME); put(0, y, 2, FRAME); }

  // Second deck with a rail and a corner light.
  square(0, 3, 16, DECK);
  put(3, 17, 1, FRAME);
  put(1, 17, 3, FRAME);
  put(3, 17, 3, LIGHT);

  // Upper shaft, top deck, spire and tip.
  for (let y = 17; y <= 21; y++) { put(1, y, 1, FRAME); put(0, y, 1, FRAME); put(1, y, 0, FRAME); }
  square(0, 1, 22, DECK);
  for (let y = 23; y <= 28; y++) put(0, y, 0, FRAME);
  put(0, 29, 0, LIGHT);

  return [...cells.values()].sort((a, b) => a[1] - b[1] || a[0] - b[0] || a[2] - b[2]);
}

const QUARTERS = [
  { key: 'leg_ne', label: 'north-east leg', sx: 1, sz: -1 },
  { key: 'leg_se', label: 'south-east leg', sx: 1, sz: 1 },
  { key: 'leg_sw', label: 'south-west leg', sx: -1, sz: 1 },
  { key: 'leg_nw', label: 'north-west leg', sx: -1, sz: -1 },
];

const local = quarter();
if (local.length !== QUARTER_BLOCKS) {
  throw new Error(`a quarter has ${local.length} blocks, expected ${QUARTER_BLOCKS}`);
}

const blocks = [];
const sections = {};
const seen = new Set();
for (const { key, label, sx, sz } of QUARTERS) {
  const start = blocks.length;
  for (const [u, y, v, block] of local) {
    const x = sx > 0 ? HALF + u : HALF - 1 - u;
    const z = sz > 0 ? HALF + v : HALF - 1 - v;
    const cell = `${x},${y},${z}`;
    if (seen.has(cell)) throw new Error(`two quarters share cell ${cell}`);
    seen.add(cell);
    blocks.push([x, y, z, block]);
  }
  sections[key] = { label, blocks: [start, blocks.length] };
}

const materials = {};
for (const [, , , block] of blocks) materials[block] = (materials[block] || 0) + 1;
const height = Math.max(...blocks.map(b => b[1])) + 1;

const payload = {
  _note: 'A 30-tall iron tower on four legs with three decks and a lit spire. 600 blocks in four 150-block legs. Creative-studio build (agorokh/hermescraft#592): too tall to place on foot. Generated by scripts/generate_eiffel_tower_schematic.mjs.',
  schema_version: 1,
  name: 'eiffel_tower',
  footprint: [HALF * 2, HALF * 2],
  height,
  materials,
  sections,
  blocks,
};

await mkdir(dirname(outFile), { recursive: true });
const lines = blocks.map(b => `    ${JSON.stringify(b)}`).join(',\n');
const head = JSON.stringify({ ...payload, blocks: [] }, null, 2).replace(/"blocks": \[\]\n\}$/, `"blocks": [\n${lines}\n  ]\n}`);
await writeFile(outFile, `${head}\n`, 'utf8');
console.log(`wrote ${outFile}: ${blocks.length} blocks, ${height} high, ${JSON.stringify(materials)}`);
